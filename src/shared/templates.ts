export function createTemplateFromStyle(
  name: string,
  style: CaptionStyle,
  category: CaptionTemplate['category'] = 'custom',
  description = ''
): CaptionTemplate {
  const id = `tpl_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
  const now = new Date().toISOString();
  return {
    schemaVersion: '1.0.0',
    id,
    name: name.trim() || 'Untitled Template',
    category,
    description: description.trim() || 'Custom typography template',
    isBuiltIn: false,
    createdAt: now,
    updatedAt: now,
    style: {
      ...style,
      presetId: id,
      templateName: name.trim() || 'Untitled Template',
    },
  };
}

export function duplicateTemplate(
  source: CaptionTemplate,
  newName?: string
): CaptionTemplate {
  const name = newName || `${source.name} (Copy)`;
  return createTemplateFromStyle(name, source.style, source.category, source.description);
}

export function exportTemplateAsJson(template: CaptionTemplate): string {
  return JSON.stringify(template, null, 2);
}

export function validateTemplateJson(
  jsonString: string
): { success: boolean; template?: CaptionTemplate; error?: string } {
  try {
    const parsed = JSON.parse(jsonString);
    const result = CaptionTemplateSchema.safeParse(parsed);
    if (!result.success) {
      const issue = result.error.issues[0];
      const errorMsg = issue ? `${issue.path.join('.')}: ${issue.message}` : 'Invalid template schema';
      return { success: false, error: errorMsg };
    }
    return { success: true, template: result.data as CaptionTemplate };
  } catch (err) {
    const msg = err instanceof Error ? err.message : 'Invalid JSON formatting';
    return { success: false, error: msg };
  }
}

export interface FilterTemplatesOptions {
  category?: CaptionTemplate['category'] | 'all';
  search?: string;
  favoritesOnly?: boolean;
  favoriteIds?: string[];
  tab?: 'all' | 'builtin' | 'custom';
}

export function filterTemplates(
  templates: CaptionTemplate[],
  options: FilterTemplatesOptions = {}
): CaptionTemplate[] {
  const { category = 'all', search = '', favoritesOnly = false, favoriteIds = [], tab = 'all' } = options;
  const searchLower = search.trim().toLowerCase();

  return templates.filter((tpl) => {
    // Tab filter
    if (tab === 'builtin' && !tpl.isBuiltIn) return false;
    if (tab === 'custom' && tpl.isBuiltIn) return false;

    // Favorites filter
    if (favoritesOnly) {
      const isFav = favoriteIds.includes(tpl.id) || !!tpl.isFavorite;
      if (!isFav) return false;
    }

    // Category filter
    if (category !== 'all') {
      if (category === 'custom') {
        if (tpl.isBuiltIn) return false;
      } else if (tpl.category !== category) {
        return false;
      }
    }

    // Search filter
    if (searchLower) {
      const matchName = tpl.name.toLowerCase().includes(searchLower);
      const matchCat = tpl.category.toLowerCase().includes(searchLower);
      const matchDesc = tpl.description ? tpl.description.toLowerCase().includes(searchLower) : false;
      const matchTags = tpl.tags ? tpl.tags.some((tag) => tag.toLowerCase().includes(searchLower)) : false;
      if (!matchName && !matchCat && !matchDesc && !matchTags) {
        return false;
      }
    }

    return true;
  });
}

export function toggleFavoriteTemplateId(id: string, currentFavorites: string[]): string[] {
  if (currentFavorites.includes(id)) {
    return currentFavorites.filter((favId) => favId !== id);
  }
  return [...currentFavorites, id];
}

